"""构造一个带真实元数据段的 JPEG 测试样本（仅用于验证，不修改项目代码）。"""
import struct
import shutil
import pathlib

SRC = "/System/Library/CoreServices/StageManagerOnboarding.app/Contents/Resources/StageManager_DK.ca/assets/MacDarkWallpaper.jpg"
OUT = pathlib.Path("/tmp/wr_test.jpg")
OUT_CLEANED = pathlib.Path("/tmp/wr_test.cleaned.jpg")

base = pathlib.Path(SRC).read_bytes()
assert base[:2] == b"\xff\xd8", "不是有效 JPEG"


def build_exif_app1() -> bytes:
    """构造最小的 TIFF/IFD0，含 Make / Model / Software 三个 ASCII 标签。"""
    make = b"TestCam\x00"                      # 8
    model = b"TestModel\x00"                   # 10
    soft = b"watermarks-remover-test\x00"      # 24
    n_entries = 3
    ifd_offset = 8
    ifd_size = 2 + n_entries * 12 + 4
    off_make = ifd_offset + ifd_size            # 50
    off_model = off_make + len(make)            # 58
    off_soft = off_model + len(model)           # 68

    tiff = bytearray()
    tiff += b"II"                                # 小端
    tiff += struct.pack("<H", 42)                # 魔数
    tiff += struct.pack("<I", ifd_offset)        # 首个 IFD 偏移
    tiff += struct.pack("<H", n_entries)
    for tag, count, offset in ((0x010F, len(make), off_make),
                               (0x0110, len(model), off_model),
                               (0x0131, len(soft), off_soft)):
        tiff += struct.pack("<HHI", tag, 2, count)   # type 2 = ASCII
        tiff += struct.pack("<I", offset)
    tiff += struct.pack("<I", 0)                 # 没有下一个 IFD
    tiff += make + model + soft

    payload = b"Exif\x00\x00" + bytes(tiff)
    return b"\xff\xe1" + struct.pack(">H", len(payload) + 2) + payload


def build_xmp_app1() -> bytes:
    xmp = (b'<?xpacket begin="\xef\xbb\xbf" id="W5M0MpCehiHzreSzNTczkc9d"?>'
           b'<x:xmpmeta xmlns:x="adobe:ns:meta/"><rdf:RDF '
           b'xmlns:rdf="http://www.w3.org/1999/02/22-rdf-syntax-ns#">'
           b'<rdf:Description xmlns:dc="http://purl.org/dc/elements/1.1/" '
           b'dc:creator="AI Generator"/></rdf:RDF></x:xmpmeta>'
           b'<?xpacket end="w"?>')
    payload = b"http://ns.adobe.com/xap/1.0/\x00" + xmp
    return b"\xff\xe1" + struct.pack(">H", len(payload) + 2) + payload


def build_jumbf_app11() -> bytes:
    """模拟 C2PA 的 JUMBF 容器放在 APP11 段里。"""
    jumbf = bytearray()
    for label, content in ((b"jumb", b"jumd"), (b"c2pa", b"c2ma")):
        box_body = bytes(content) + b"test-manifest-payload"
        jumbf += struct.pack(">I", len(box_body) + 8) + bytes(label) + box_body
    payload = bytes(jumbf)
    return b"\xff\xeb" + struct.pack(">H", len(payload) + 2) + payload


def build_comment() -> bytes:
    payload = b"Generated by AI image model - do not redistribute"
    return b"\xff\xfe" + struct.pack(">H", len(payload) + 2) + payload


def build_ai_software_app1() -> bytes:
    """带 AI 生成器提示的 APP1（非 Exif/XMP，模拟厂商写出的软件标识）。"""
    payload = b"MIDJOURNEY-AI-GENERATOR-v6\x00ns.adobe.com"
    return b"\xff\xe1" + struct.pack(">H", len(payload) + 2) + payload


injected = (build_exif_app1() + build_xmp_app1()
            + build_jumbf_app11() + build_comment() + build_ai_software_app1())

OUT.write_bytes(base[:2] + injected + base[2:])
print(f"原始 JPEG : {len(base):,} 字节")
print(f"注入段    : {len(injected):,} 字节 (Exif/XMP/JUMBF-C2PA/Comments/AI-software)")
print(f"样本输出  : {OUT}  {OUT.stat().st_size:,} 字节")
